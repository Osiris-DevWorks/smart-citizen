class TestGeneratedText:
    def test_english_run_writes_english(self):
        gen = _load_generator()
        gen._set_text_language("english")
        assert gen._t("Max HP") == "Max HP"
        assert gen._t("{count} items", count=3) == "3 items"
        assert gen._localize_separators("x\\n\\n--- STATS ---\\ny") == "x\\n\\n--- STATS ---\\ny"

    def test_translated_run_writes_the_table(self, monkeypatch):
        gen = _load_generator()
        monkeypatch.setattr(gen, "_load_text_table", lambda lang: {
            "Max HP": "Max. TP", "{count} items": "{count} Teile",
            "--- STATS ---": "--- WERTE ---", "Standard": "Normal",
        })
        gen._set_text_language("german")
        try:
            assert gen._t("Max HP") == "Max. TP"
            assert gen._t("Regen") == "Regen"  # no entry: English
            assert gen._t("{count} items", count=3) == "3 Teile"
            assert (gen._localize_separators("a\\n\\n--- STATS ---\\nb")
                    == "a\\n\\n--- WERTE ---\\nb")
        finally:
            gen._set_text_language(None)

    def test_mission_details_use_the_table(self, monkeypatch):
        from lxml import etree as ET
        gen = _load_generator()
        monkeypatch.setattr(gen, "_load_text_table", lambda lang: {
            "Engagement Type": "Einsatzart", "Ship": "Schiff",
            "Mission Type": "Missionsart", "Standard": "Normal",
            "Unique": "Einmalig",
        })
        root = ET.fromstring('<MissionBrokerEntry onceOnly="1"/>')
        english = gen.enhancements_mission(root)
        gen._set_text_language("german")
        try:
            german = gen.enhancements_mission(root)
        finally:
            gen._set_text_language(None)
        assert "<EM4>Engagement Type:</EM4> Ship" in english
        assert "<EM4>Mission Type:</EM4> Unique" in english
        assert "<EM4>Einsatzart:</EM4> Schiff" in german
        assert "<EM4>Missionsart:</EM4> Einmalig" in german

    def test_write_ini_swaps_the_section_label(self, tmp_path, monkeypatch):
        gen = _load_generator()
        monkeypatch.setattr(gen, "_load_text_table",
                            lambda lang: {"--- STATS ---": "--- WERTE ---"})
        gen._set_text_language("german")
        try:
            out = tmp_path / "x.ini"
            gen.write_ini(out, {"k": "desc\\n\\n--- STATS ---\\nMax HP: 5"})
        finally:
            gen._set_text_language(None)
        assert out.read_text(encoding="utf-8").strip() == "k=desc\\n\\n--- WERTE ---\\nMax HP: 5"

    def test_language_is_read_from_a_translated_base_ini_path(self, tmp_path, monkeypatch):
        """A CLI run over cache/lang/<language>/base.ini writes that language."""
        gen = _load_generator()
        seen = []
        monkeypatch.setattr(gen, "_load_text_table", lambda lang: seen.append(lang) or {})
        base = tmp_path / "lang" / "german" / "base.ini"
        base.parent.mkdir(parents=True)
        base.write_text("a=b\n", encoding="utf-8")
        with pytest.raises(FileNotFoundError):  # no DataForge cache: stops after the parse
            gen.main(base, tmp_path / "missing")
        assert seen == ["german"]


class TestTheStamp:
    def test_english_stamp_is_the_build_key(self):
        from src.utils.settings import AppSettings
        assert AppSettings.enhancements_stamp_value("123", "english") == "123"

    def test_translated_stamp_carries_its_table(self):
        from src.utils.enhancement_text import table_fingerprint
        from src.utils.settings import AppSettings
        value = AppSettings.enhancements_stamp_value("123", "german")
        assert value == f"123|text={table_fingerprint('german')}"

    def test_a_table_change_makes_the_set_stale(self, monkeypatch):
        from src.utils import enhancement_text
        from src.utils.settings import AppSettings
        monkeypatch.setattr(AppSettings, "get_dataforge_build_key",
                            staticmethod(lambda forge_dir=None: "123"))
        monkeypatch.setattr(AppSettings, "get_enhancements_stamp",
                            staticmethod(lambda language=None: "123|text=aaaaaaaaaaaa"))
        monkeypatch.setattr(enhancement_text, "table_fingerprint", lambda lang: "aaaaaaaaaaaa")
        assert AppSettings.enhancements_built_from_current_dataforge("german")
        monkeypatch.setattr(enhancement_text, "table_fingerprint", lambda lang: "bbbbbbbbbbbb")
        assert not AppSettings.enhancements_built_from_current_dataforge("german")


if __name__ == "__main__":
    if sys.argv[1:] == ["--write"]:
        ENGLISH_LIST.write_text(english_list_json(expected_texts()), encoding="utf-8")
        print(f"Wrote {ENGLISH_LIST}")
    else:
        print("usage: python tests/test_enhancement_text.py --write")
